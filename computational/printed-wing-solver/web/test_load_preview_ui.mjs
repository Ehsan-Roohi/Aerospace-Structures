import assert from 'node:assert/strict';
import {JSDOM,loadBeamLab} from './beam_test_dom.mjs';
const dom=new JSDOM('<div id="foundations"></div>',{url:'https://example.org',runScripts:'outside-only'}),w=dom.window;
const {$}=loadBeamLab(dom),state=()=>w.BeamLab.state();
$('#beamleftSupport').value='fixed';$('#beamSolve').click(); // Deliberate test fixture, not a default support.
const set=(id,value)=>{$('#'+id).value=value;$('#'+id).dispatchEvent(new w.Event('input',{bubbles:true}));};
$('#beamLoadKind').value='elliptic';$('#beamLoadKind').dispatchEvent(new w.Event('change'));
set('beamLoadA',0);set('beamLoadB',450);set('beamCurveValue',1000);
assert.ok($('#beamLoadPreview').textContent.includes('Total force F = 1000 N'));
assert.equal(state().model.loads.length,0);
$('#beamLoadForm').dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}));
const result=state().solved.result;
assert.ok($('#beamLoads').querySelector('.load-profile-preview'));
$('#beamLoadScale').value='independent';$('#beamLoadScale').dispatchEvent(new w.Event('change'));
assert.equal(state().solved.result,result,'display scale never changes the solved physics');assert.ok($('#beamPictureNote').textContent.includes('do NOT compare'));
$('#beamClear').click();
set('beamPowerA',0);set('beamPowerB',450);set('beamPowerF',20);set('beamPowerN',3);$('#beamPowerPreview').click();
assert.equal(state().model.loads.length,0,'generator only previews');assert.ok($('#beamCsvText').value.split('\n').length===32);
assert.ok($('#beamCsvResult').textContent.includes('31 rows'));assert.equal($('#beamCsvApply').disabled,false);
$('#beamCsvApply').click();assert.equal(state().model.loads.length,1);assert.ok(Math.abs(state().solved.result.resultant-20)<1e-8);
console.log('Beam preview UI: live curve and saved-load figures, no default force, scale leaves solution unchanged, power table preview then explicit apply passed.');
dom.window.close();
