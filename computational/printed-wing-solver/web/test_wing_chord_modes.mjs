change('wgRoot',160);assert.equal(ctx.S.geometry.tipChord,72);assert.equal(Number($('#wgTaper').value),.45);
assert.equal('taper' in ctx.S.geometry,false,'only canonical chord lengths are stored for JSON/CAD');
console.log('PASS: main-panel chord modes, calculated read-only fields, root edits preserve the selected independent input, canonical JSON geometry unchanged.');
dom.window.close();
