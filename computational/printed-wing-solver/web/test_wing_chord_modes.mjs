import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import vm from 'node:vm';
const require=createRequire(import.meta.url),{JSDOM}=require(process.env.MIE446_JSDOM_MODULE||'jsdom');
const dom=new JSDOM('<div id="wingGeometryForm"></div><span id="wlGeometryBadge"></span>');
const w=dom.window,$=s=>w.document.querySelector(s);
const src=readFileSync(new URL('./wing_lab_template.html',import.meta.url),'utf8');
const ctx={window:w,document:w.document,$,S:{geometry:{rootChord:160,tipChord:128,semiSpan:450,modules:3},emptyStudy:false},fieldErrors:{},airfoilLabel:()=> 'NACA 2412',nf:(v,d)=>v.toFixed(d),mm:v=>v+' mm',esc:String,openAdvancedGeometryPopup(){},numberFrom:n=>n.value.trim()===''?NaN:Number(n.value)};
